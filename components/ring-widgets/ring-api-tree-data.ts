/**
 * Ring API tree — founder-friendly catalog of App Router `/api/*` routes.
 * Source of truth: Next.js build route list (ring-platform.org, 2026-07-10).
 * Methods are the common verbs for each path; see route handlers for exact exports.
 */

export type ApiHttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'

export type ApiEndpointNode = {
  id: string
  path: string
  /** Short founder-facing title */
  title: string
  /** Plain-language what this endpoint does */
  summary: string
  methods: ApiHttpMethod[]
  /** Optional deep-doc path under /docs/... */
  docsHref?: string
}

export type ApiFamilyNode = {
  id: string
  label: string
  /** One-line founder pitch for the family */
  blurb: string
  /** Family procedure / domain doc — used when a leaf has no docsHref */
  docsHref?: string
  /** Short label for the docs link (founder-friendly) */
  docsLabel?: string
  endpoints: ApiEndpointNode[]
}

function ep(
  path: string,
  title: string,
  summary: string,
  methods: ApiHttpMethod[],
  docsHref?: string,
): ApiEndpointNode {
  return {
    id: path,
    path: `/api/${path}`,
    title,
    summary,
    methods,
    docsHref,
  }
}

