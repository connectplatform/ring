export const API_TREE_ROUTE_COUNT = API_TREE_FAMILIES.reduce(
  (n, f) => n + f.endpoints.length,
  0,
)

export function findEndpoint(id: string): {
  family: ApiFamilyNode
  endpoint: ApiEndpointNode
} | null {
  for (const family of API_TREE_FAMILIES) {
    const endpoint = family.endpoints.find((e) => e.id === id)
    if (endpoint) return { family, endpoint }
  }
  return null
}
